// bun test .dev/test/calc.test.ts
import { expect, test } from "bun:test";
import { calc, show } from "../../src/calc";

const ok: [string, string, boolean?][] = [
  ["1+2*3", "7"],
  ["(1+2)*3", "9"],
  ["2^3^2", "512"],
  ["-2^2", "-4"],
  ["2^-1", "0.5"],
  ["0.1+0.2", "0.3"],
  ["10/4", "2.5"],
  ["15%*80", "12"],
  ["50%", "0.5"],
  ["5!", "120"],
  ["2π", "6.2831853071796"],
  ["3(1+2)", "9"],
  ["2sqrt(9)", "6"],
  ["√16", "4"],
  ["sqrt 16 + 1", "5"],
  ["sin(30)", "0.5"],
  ["cos 60", "0.5"],
  ["tan(45)", "1"],
  ["sin(pi/2)", "1", false],
  ["asin(1)", "90"],
  ["log(1000)", "3"],
  ["log(8, 2)", "3"],
  ["ln(e)", "1"],
  ["0xff+1", "256"],
  ["0b101", "5"],
  ["0o17", "15"],
  ["17 mod 5", "2"],
  ["-7 mod 3", "2"],
  ["round(3.14159, 2)", "3.14"],
  ["max(1, 5, 3)", "5"],
  ["（1＋2）×3÷9", "1"],
  ["2**10", "1024"],
  ["(1+2", "3"],
  ["1e3+1", "1001"],
  ["ans*2", "84"],
  ["1/3", "0.33333333333333"],
  ["2^70", "1.1805916207174e21"],
  ["123456789*1000", "123456789000"],
];

test("calc", () => {
  for (const [e, want, deg] of ok) expect([e, show(calc(e, deg ?? true, 42))]).toEqual([e, want]);
});

test("errors", () => {
  for (const e of ["", "1/0", "1+", "(1+2))", "foo(1)", "sqrt(-1)", "2 # 3", "tan(90)", "171!", "1.5!"]) expect(() => calc(e)).toThrow();
});
